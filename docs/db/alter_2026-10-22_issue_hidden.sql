ALTER TABLE number_issue
  ADD COLUMN hidden_at DATETIME NULL COMMENT '[추가 2026-10-22] 사용자가 이 기기 발급 내역 목록에서 지운 시각. NULL 이면 목록에 보인다' AFTER created_at;
