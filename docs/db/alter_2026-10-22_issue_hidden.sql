-- 이미 만들어 둔 DB 에서 한 번만 실행한다. (이미 실행한 DB 에서는 다시 실행하지 말 것: 컬럼이 이미 있다는 오류가 난다)
-- schema.sql 로 DB 를 새로 만든다면 이미 hidden_at 이 들어 있으므로 이 파일은 실행하지 않는다.
--
-- 바꾼 이유
--  사용자가 오래된 발급 내역을 이 기기 목록에서 지울 수 있게 한다. 기록 자체는 지우지 않는다. (당첨 검증·통계·발급코드 조회 유지)
--  그래서 행을 삭제하지 않고 "지운 시각"만 남긴다. NULL 이면 목록에 보이고, 값이 있으면 목록에서만 빠진다.
